CREATE TEMP FUNCTION CLEAN_TEXT(value STRING)
RETURNS STRING
LANGUAGE js AS """
  if (value === null) return null;

  return value
    .replace(/[^A-Za-z0-9]+/g, ' ')
    .replace(/(.)\\1{2,}/g, '$1')
    .trim();
""";
CREATE OR REPLACE TABLE `SILVER_LAYER.SILVER_LEAD` AS
     WITH location_country AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'Country'
    ),
    location_state AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'State'
    ),
    location_city AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'City'
    )
    SELECT
        l.LEAD_ID,
        FARM_FINGERPRINT(CONCAT(UPPER(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(l.COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' '))),'|',CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(l.MAIL_DOMAIN)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN UPPER(TRIM(LOWER(l.MAIL_DOMAIN))) ELSE 'Not Available' END )) AS COMPANY_ID,
        TRIM( INITCAP( REGEXP_REPLACE(CLEAN_TEXT(l.FIRST_NAME), r'[^A-Za-z0-9]+', ' ') ) ) AS FIRST_NAME,
        TRIM( INITCAP( REGEXP_REPLACE(CLEAN_TEXT(l.LAST_NAME), r'[^A-Za-z0-9]+', ' ') ) ) AS LAST_NAME,
        l.SALUTATION_ID,
        s.SALUTATION_DESC AS SALUTATION_DESC,
        TRIM(INITCAP(REGEXP_REPLACE(CLEAN_TEXT(l.JOB_TITLE), r'[^A-Za-z]+', ' ')  )) AS JOB_TITLE,
        l.JOB_LEVEL_ID,
        jl.JOB_LEVEL_DESC AS JOB_LEVEL_DESC,
        l.JOBFUNCTION_ID,
        jf.JOBFUNCTION_DESC AS JOBFUNCTION_DESC,
        CASE WHEN l.TENURITY IS NULL THEN 'NA' WHEN REGEXP_CONTAINS(UPPER(l.TENURITY), 'HTTPS?://') THEN NULL
            ELSE CONCAT( COALESCE( NULLIF( REGEXP_REPLACE(REGEXP_EXTRACT(UPPER(l.TENURITY), r'[0-9]{1,3}[ ]*(?:YEAR|YEARS|YR|YRS|Y)'),'[^0-9]',''),''),'0'),' Years ',COALESCE(
            NULLIF(REGEXP_REPLACE(REGEXP_EXTRACT(UPPER(l.TENURITY),r'[0-9]{1,2}[ ]*(?:MONTH|MONTHS|MON|MONS|MOS|M)'),'[^0-9]',''),''),'0'),' Months') END AS TENURITY,
        CASE  WHEN REGEXP_CONTAINS(TRIM(LOWER(l.EMAIL_ID)),r'^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'  )  
            THEN TRIM(LOWER(l.EMAIL_ID))  ELSE   'Not Available' END AS EMAIL_ID,
        l.MD5_EMAIL_ID,
        CASE  WHEN REGEXP_CONTAINS(TRIM(LOWER(l.mail_domain)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'  )  
            THEN TRIM(LOWER(l.mail_domain))  ELSE   'Not Available' END AS MAIL_DOMAIN,
        CASE WHEN NULLIF(TRIM(l.PHONE_NUMBER), '') IS NULL THEN '00000000' 
            WHEN REGEXP_CONTAINS( REGEXP_REPLACE( REGEXP_REPLACE(TRIM(l.PHONE_NUMBER), r'[^0-9]', ''), r'^0+', '' ), r'^[1-9][0-9]{6,14}$' ) 
            THEN REGEXP_REPLACE( REGEXP_REPLACE(TRIM(l.PHONE_NUMBER), r'[^0-9]', ''), r'^0+', '' ) ELSE '0000000000' END AS PHONE_NUMBER,
        CASE WHEN NULLIF(TRIM(l.COUNTRY_CODE), '') IS NULL THEN '00'
        WHEN TRIM(l.COUNTRY_CODE) IN ('0', '00') THEN '00'
        WHEN REGEXP_CONTAINS(TRIM(l.COUNTRY_CODE), r'^\+?[0-9]{1,3}$')
        THEN REGEXP_REPLACE(TRIM(l.COUNTRY_CODE), r'^\+', '')
        ELSE '00' END  AS COUNTRY_CODE,
        CASE WHEN NULLIF(TRIM(l.MOBILE_NO), '') IS NULL THEN '0000000000'
            WHEN REGEXP_CONTAINS(REGEXP_REPLACE(TRIM(l.MOBILE_NO), r'[^0-9]', ''),r'^[1-9][0-9]{9,14}$')  
            THEN REGEXP_REPLACE(TRIM(l.MOBILE_NO), r'[^0-9]', '')  ELSE '0000000000' END AS MOBILE_NO,
        CASE WHEN NULLIF(TRIM(l.DIRECT_DIAL_EXTENSION), '') IS NULL THEN '0'
            WHEN REGEXP_CONTAINS(TRIM(l.DIRECT_DIAL_EXTENSION), r'^[1-9][0-9]{0,5}$')
            THEN TRIM(l.DIRECT_DIAL_EXTENSION)  ELSE '0' END AS DIRECT_DIAL_EXTENSION,
        TRIM(REGEXP_REPLACE(REGEXP_REPLACE(COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' ')) AS COMPANY_NAME,
        TRIM( INITCAP( REGEXP_REPLACE( REGEXP_REPLACE( l.ADDRESS1, r'[^\p{L}\p{N}\s.,/#()&-]', ' ' ), r'\s+', ' ' ) ) ) AS ADDRESS1,
        TRIM( INITCAP( REGEXP_REPLACE( REGEXP_REPLACE( l.ADDRESS2, r'[^\p{L}\p{N}\s.,/#()&-]', ' ' ), r'\s+', ' ' ) ) ) AS ADDRESS2,
        at_tag.ADDRESS_TAG_DESC AS ADDRESS_TAG_DESC,
        CASE WHEN NULLIF(TRIM(l.ZIP_CODE), '') IS NULL THEN 'Not Available' WHEN REGEXP_CONTAINS(
            TRIM(l.ZIP_CODE), r'^[A-Za-z0-9][A-Za-z0-9 -]{2,9}$' )THEN UPPER(TRIM(l.ZIP_CODE)) ELSE 'Not Available' END AS ZIP_CODE,
        l.COUNTRY_ID,
        lc.LOCATION_DESC AS COUNTRY_DESC,
        l.STATE_ID,
        ls.LOCATION_DESC AS STATE_DESC,
        l.CITY_ID,
        lci.LOCATION_DESC AS CITY_DESC,
        UPPER(TRIM(l.TIMEZONE_ABBR)) AS TIMEZONE_ABBR,
        TRIM(INITCAP( REGEXP_REPLACE(l.INDUSTRY, r'[^A-Za-z0-9]+', ' ') ) ) AS INDUSTRY,
        l.STANDARD_INDUSTRY_ID,
        si.STANDARD_INDUSTRY_DESC AS STANDARD_INDUSTRY_DESC,
        UPPER(TRIM(l.SIC_CODE)) AS SIC_CODE,
        UPPER(TRIM(l.NAICS_CODE)) AS NAICS_CODE,
        l.EMPLOYEE_SIZE_ID,
        es.EMPLOYEE_SIZE_DESC AS EMPLOYEE_SIZE_DESC,
        TRIM(l.ACTUAL_EMPLOYEE_SIZE) AS ACTUAL_EMPLOYEE_SIZE,
        l.REVENUE_SIZE_ID,
        rs.REVENUE_SIZE_DESC AS REVENUE_SIZE_DESC,
        l.CONTACT_SUCCESS_ATTEMPTS,
        l.DATAREUSE_ASIS_UNTIL_DT,
        l.ISMISUPLOAD AS IS_MIS_UPLOAD,
        l.ISUSERUPLOAD AS IS_USER_UPLOAD,
        l.ISPURCHASEDATA AS IS_PURCHASED_DATA,
        l.UPLOADED_DT,
        l.UPLOADED_BY,
        u_up.USER_FULL_NAME AS UPLOADED_BY_NAME,
        ARRAY_TO_STRING(REGEXP_EXTRACT_ALL(MULTI_UPLOADEDBY, r'\d+'),', ') AS MULTI_UPLOADED_BY,
        l.UNVR_ID,
        l.ORDERKEYID AS ORDER_KEY_ID_DIRECT,
        TRIM(LOWER(l.SUGGESTEDEMAIL_ID)) AS SUGGESTED_EMAIL_ID,
        l.ISDELETE AS IS_DELETED,
        l.EDITED_DT,
        l.EDITED_BY,
        u_ed.USER_FULL_NAME AS EDITED_BY_NAME,
        CURRENT_TIMESTAMP() AS SOURCE_LOADED_AT
    FROM `BRONZE_LAYER.TBLLEADS_MASTERLIST` l
    INNER JOIN `BRONZE_LAYER.MST_TBLSALUTATION` s ON l.SALUTATION_ID = s.SALUTATION_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLJOBLEVEL` jl ON l.JOB_LEVEL_ID = jl.JOB_LEVEL_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLJOBFUNCTION` jf ON l.JOBFUNCTION_ID = jf.JOBFUNCTION_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLADDRESSTAG` at_tag ON l.ADDRESS_TAG_ID = at_tag.ADDRESS_TAG_ID
    INNER JOIN location_country lc ON l.COUNTRY_ID = lc.LOCATION_ID
    INNER JOIN location_state ls ON l.STATE_ID = ls.LOCATION_ID
    INNER JOIN location_city lci ON l.CITY_ID = lci.LOCATION_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLSTANDARDINDUSTRY` si ON l.STANDARD_INDUSTRY_ID = si.STANDARD_INDUSTRY_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLEMPLOYEESIZE` es ON l.EMPLOYEE_SIZE_ID = es.EMPLOYEE_SIZE_ID
    INNER JOIN `BRONZE_LAYER.MST_TBLREVENUESIZE` rs ON l.REVENUE_SIZE_ID = rs.REVENUE_SIZE_ID
    INNER JOIN `SILVER_LAYER.SILVER_USER` u_up ON l.UPLOADED_BY = u_up.USER_ID
    INNER JOIN `SILVER_LAYER.SILVER_USER` u_ed ON l.EDITED_BY = u_ed.USER_ID    ;

