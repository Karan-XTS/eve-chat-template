CREATE OR REPLACE TABLE `SILVER_LAYER.SILVER_DELIVERY` AS
    WITH delivery_lead_map AS (
        SELECT RECORD_ID, LEAD_ID
        FROM `BRONZE_LAYER.TBLLEADS_STATUS_ACTIVITY_TRACKER`
        QUALIFY ROW_NUMBER() OVER (PARTITION BY RECORD_ID ORDER BY INSERTED_DT DESC, RECORD_ID DESC) = 1
    )
    SELECT
        d.RECORD_ID,
        dlm.LEAD_ID,
        TRIM(d.ORDER_ID) AS ORDER_ID,
        UPPER(TRIM(d.CLIENT_NAME)) AS CLIENT_NAME,
        UPPER(TRIM(d.CAMPAIGN_NAME)) AS CAMPAIGN_NAME,
        d.DELIVERY_DT,
        TRIM( INITCAP( REGEXP_REPLACE(d.FIRSTNAME, r'[^A-Za-z0-9]+', ' ') ) ) AS FIRSTNAME,
        TRIM( INITCAP( REGEXP_REPLACE(d.LASTNAME, r'[^A-Za-z0-9]+', ' ') ) ) AS LASTNAME,
        TRIM(REGEXP_REPLACE(REGEXP_REPLACE(COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' ')) AS COMPANY_NAME,
        CASE WHEN (TRIM(d.PHONE_NUMBER), '') IS NULL THEN '0000000000'
            WHEN REGEXP_CONTAINS(REGEXP_REPLACE(TRIM(d.PHONE_NUMBER), r'[^0-9]', ''),r'^[1-9][0-9]{9,14}$')  
            THEN REGEXP_REPLACE(TRIM(d.PHONE_NUMBER), r'[^0-9]', '')  ELSE '0000000000' END AS PHONE_NUMBER,
        CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(EMAIL_ID)),r'^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'  )  
            THEN TRIM(LOWER(EMAIL_ID))  ELSE   'Not Available' END AS EMAIL_ID, 
        CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(MAIL_DOMAIN)),r'[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'  )  
            THEN TRIM(LOWER(MAIL_DOMAIN))  ELSE   'Not Available' END AS MAIL_DOMAIN, 
        TRIM(d.LEADTYPE_DESC) AS LEADTYPE_DESC,
        TRIM(d.JOB_TITLE_LINK) AS JOB_TITLE_LINK,
        d.UPLOADED_DT,
        d.UPLOADED_BY,
        u.USER_FULL_NAME AS UPLOADED_BY_NAME,
        CURRENT_TIMESTAMP() AS SOURCE_LOADED_AT
    FROM `BRONZE_LAYER.TBLMISDELIVERED_LEADS` d
     JOIN delivery_lead_map dlm ON dlm.RECORD_ID = d.RECORD_ID
     JOIN `SILVER_LAYER.SILVER_USER` u ON d.UPLOADED_BY = u.USER_ID;

