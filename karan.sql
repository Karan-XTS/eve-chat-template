-- 1.3 SILVER_COMPANY (EXISTING - unchanged)
-- Grain: One row per company (derived from leads)
-- Business Key: COMPANY_ID
-- ============================================================
CREATE OR REPLACE TABLE `SILVER_LAYER.SILVER_COMPANY` AS
    WITH company_base AS (
        SELECT
            FARM_FINGERPRINT(CONCAT(UPPER(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(l.COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' '))),'|',CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(l.MAIL_DOMAIN)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN UPPER(TRIM(LOWER(l.MAIL_DOMAIN))) ELSE 'Not Available' END )) AS COMPANY_ID,
            TRIM(REGEXP_REPLACE(REGEXP_REPLACE(COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' ')) AS COMPANY_NAME,
            CASE  WHEN REGEXP_CONTAINS(TRIM(LOWER(l.mail_domain)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'  )  
            THEN TRIM(LOWER(l.mail_domain))  ELSE   'Not Available' END AS MAIL_DOMAIN,
            TRIM(INITCAP( REGEXP_REPLACE(CLEAN_TEXT(l.INDUSTRY), r'[^A-Za-z0-9]+', ' ') ) ) AS INDUSTRY,
            l.STANDARD_INDUSTRY_ID,
            si.STANDARD_INDUSTRY_DESC AS STANDARD_INDUSTRY_DESC,
            TRIM(l.ACTUAL_EMPLOYEE_SIZE) AS ACTUAL_EMPLOYEE_SIZE,
            l.EMPLOYEE_SIZE_ID,
            es.EMPLOYEE_SIZE_DESC AS EMPLOYEE_SIZE_DESC,
            l.REVENUE_SIZE_ID,
            rs.REVENUE_SIZE_DESC AS REVENUE_SIZE_DESC,
            UPPER(TRIM(l.SIC_CODE)) AS SIC_CODE,
            UPPER(TRIM(l.NAICS_CODE)) AS NAICS_CODE,
        TRIM( INITCAP( REGEXP_REPLACE( REGEXP_REPLACE( l.ADDRESS1, r'[^\p{L}\p{N}\s.,/#()&-]', ' ' ), r'\s+', ' ' ) ) ) AS ADDRESS1,
        TRIM( INITCAP( REGEXP_REPLACE( REGEXP_REPLACE( l.ADDRESS2, r'[^\p{L}\p{N}\s.,/#()&-]', ' ' ), r'\s+', ' ' ) ) ) AS ADDRESS2,
            l.COUNTRY_ID,
            l.STATE_ID,
            l.CITY_ID,
            CASE WHEN NULLIF(TRIM(l.ZIP_CODE), '') IS NULL THEN 'Not Available' WHEN REGEXP_CONTAINS(
            TRIM(l.ZIP_CODE), r'^[A-Za-z0-9][A-Za-z0-9 -]{2,9}$' )THEN UPPER(TRIM(l.ZIP_CODE)) ELSE 'Not Available' END AS ZIP_CODE,
            l.UPLOADED_DT,
            l.EDITED_DT,
            ROW_NUMBER() OVER (PARTITION BY FARM_FINGERPRINT(CONCAT(UPPER(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(l.COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' '))),'|',CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(l.MAIL_DOMAIN)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN UPPER(TRIM(LOWER(l.MAIL_DOMAIN))) ELSE 'Not Available' END ))  ORDER BY l.EDITED_DT DESC NULLS LAST) AS RN
        FROM `BRONZE_LAYER.TBLLEADS_MASTERLIST` l
        inner JOIN `BRONZE_LAYER.MST_TBLSTANDARDINDUSTRY` si ON l.STANDARD_INDUSTRY_ID = si.STANDARD_INDUSTRY_ID
        inner JOIN `BRONZE_LAYER.MST_TBLEMPLOYEESIZE` es ON l.EMPLOYEE_SIZE_ID = es.EMPLOYEE_SIZE_ID
        inner JOIN `BRONZE_LAYER.MST_TBLREVENUESIZE` rs ON l.REVENUE_SIZE_ID = rs.REVENUE_SIZE_ID
        WHERE TRIM(l.COMPANY_NAME) !='' AND TRIM(l.MAIL_DOMAIN) != ''
    ),
    location_country AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'Country'
    ),
    location_state AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'State'
    ),
    location_city AS (
        SELECT LOCATION_ID, TRIM(INITCAP(LOCATION_DESC)) AS LOCATION_DESC 
        FROM `BRONZE_LAYER.MST_TBLLOCATIONELEMENTS` WHERE LOCATION_TYPE = 'City'
    ),
    company_agg AS (
        SELECT
            FARM_FINGERPRINT(CONCAT(UPPER(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' '))),'|',CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(MAIL_DOMAIN)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN UPPER(TRIM(LOWER(MAIL_DOMAIN))) ELSE 'Not Available' END )) AS COMPANY_ID,    
            COUNT(*) AS LEAD_COUNT,
            MIN(UPLOADED_DT) AS FIRST_SEEN_DT,
            MAX(UPLOADED_DT) AS LAST_SEEN_DT
        FROM `BRONZE_LAYER.TBLLEADS_MASTERLIST`
        WHERE TRIM(COMPANY_NAME) != '' AND TRIM(MAIL_DOMAIN) != ''
        GROUP BY FARM_FINGERPRINT(CONCAT(UPPER(TRIM(REGEXP_REPLACE(REGEXP_REPLACE(COMPANY_NAME,r'[^\p{L}\p{N}\s]',' '),r'\s+',' '))),'|',CASE WHEN REGEXP_CONTAINS(TRIM(LOWER(MAIL_DOMAIN)),r'^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$') THEN UPPER(TRIM(LOWER(MAIL_DOMAIN))) ELSE 'Not Available' END )) 
    )
    SELECT
        cb.COMPANY_ID,
        cb.COMPANY_NAME,
        cb.MAIL_DOMAIN,
        cb.INDUSTRY,
        cb.STANDARD_INDUSTRY_ID,
        cb.STANDARD_INDUSTRY_DESC,
        cb.ACTUAL_EMPLOYEE_SIZE,
        cb.EMPLOYEE_SIZE_ID,
        cb.EMPLOYEE_SIZE_DESC,
        cb.REVENUE_SIZE_ID,
        cb.REVENUE_SIZE_DESC,
        cb.SIC_CODE,
        cb.NAICS_CODE,
        cb.ADDRESS1,
        cb.ADDRESS2,
        cb.COUNTRY_ID,
        lc.LOCATION_DESC AS COUNTRY_DESC,
        cb.STATE_ID,
        ls.LOCATION_DESC AS STATE_DESC,
        cb.CITY_ID,
        lci.LOCATION_DESC AS CITY_DESC,
        cb.ZIP_CODE,
        ca.LEAD_COUNT,
        ca.FIRST_SEEN_DT,
        ca.LAST_SEEN_DT,
        CURRENT_TIMESTAMP() AS SOURCE_LOADED_AT
    FROM company_base cb
    INNER JOIN location_country lc ON cb.COUNTRY_ID = lc.LOCATION_ID
    INNER JOIN location_state ls ON cb.STATE_ID = ls.LOCATION_ID
    INNER JOIN location_city lci ON cb.CITY_ID = lci.LOCATION_ID
    INNER JOIN company_agg ca ON cb.COMPANY_ID = ca.COMPANY_ID
    WHERE cb.RN = 1;

